def generate_abstract_draft(all_papers_data):
    """
    Generates a synthetic abstract draft by extracting research problems, approaches,
    and key findings from a list of paper dictionaries.
    """
    research_problems = []
    approaches_used = []
    key_findings = []

    for paper in all_papers_data:
        problem_text = paper.get('abstract') or paper.get('introduction', '')
        if problem_text:
            sentences = nltk.sent_tokenize(problem_text)
            research_problems.append('. '.join(sentences[:2]).strip() + ('.' if sentences and sentences[0].strip() else ''))

        method_text = paper.get('methods', '')
        if method_text:
            sentences = nltk.sent_tokenize(method_text)
            approaches_used.append('. '.join(sentences[:2]).strip() + ('.' if sentences and sentences[0].strip() else ''))

        findings_text = paper.get('results') or paper.get('conclusion', '')
        if findings_text:
            sentences = nltk.sent_tokenize(findings_text)
            key_findings.append('. '.join(sentences[:2]).strip() + ('.' if sentences and sentences[0].strip() else ''))

    abstract_draft = f"This review investigates various {', '.join(set(research_problems))} " \
                     f"Different {', '.join(set(approaches_used))} were employed across studies. " \
                     f"Key findings reveal {', '.join(set(key_findings))}"
    return abstract_draft
