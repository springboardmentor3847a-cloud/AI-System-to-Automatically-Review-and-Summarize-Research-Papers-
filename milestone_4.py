import re

def generate_apa_reference(paper):
    """
    Generates an APA 7th edition style reference string for a given paper.
    Handles author formatting, title casing, and journal italicization.
    """
    authors = paper.get("authors", [])
    year = paper.get("year")
    title = paper.get("title")
    journal = paper.get("journal")


    author_str = ""
    if authors:
        if len(authors) > 7:

            formatted_authors = []
            for i, author in enumerate(authors[:6]):
                parts = author.split()
                last_name = parts[-1]
                initials = ". ".join([p[0] for p in parts[:-1] if p]) + "."
                formatted_authors.append(f"{last_name}, {initials}")

            last_author_parts = authors[-1].split()
            last_author_last_name = last_author_parts[-1]
            last_author_initials = ". ".join([p[0] for p in last_author_parts[:-1] if p]) + "."

            author_str = f"{', '.join(formatted_authors)}, ... {last_author_last_name}, {last_author_initials}"
        else:

            formatted_authors = []
            for i, author in enumerate(authors):
                parts = author.split()
                last_name = parts[-1]
                initials = ". ".join([p[0] for p in parts[:-1] if p]) + "."
                formatted_authors.append(f"{last_name}, {initials}")

            if len(formatted_authors) > 1:
                author_str = f"{', '.join(formatted_authors[:-1])}, & {formatted_authors[-1]}"
            else:
                author_str = formatted_authors[0]


    year_str = f"({year})." if year else "(n.d.)."



    def to_sentence_case(text):
        if not text: return ""
        text = text.lower()
        text = text[0].upper() + text[1:]
        text = re.sub(r':\s*([a-z])', lambda pat: ': ' + pat.group(1).upper(), text)
        return text

    title_str = to_sentence_case(title) + "."


    journal_str = f"<i>{journal}</i>." if journal else ""


    apa_reference = f"{author_str} {year_str} {title_str} {journal_str}"
    return apa_reference.strip()



