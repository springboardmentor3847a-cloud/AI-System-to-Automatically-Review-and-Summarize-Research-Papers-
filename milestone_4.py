import requests
import os

def download_pdf(pdf_url, title):
    """Downloads a PDF from a given URL and saves it to the 'downloaded_pdfs' directory."""
    if not pdf_url:
        print(f"No PDF URL available for '{title}'. Skipping download.")
        return

    # Sanitize title for filename
    safe_title = "".join(c for c in title if c.isalnum() or c in (' ', '.', '_')).rstrip()
    safe_title = safe_title.replace(" ", "_")
    filename = f"{safe_title}.pdf"
    filepath = os.path.join("downloaded_pdfs", filename)

    os.makedirs("downloaded_pdfs", exist_ok=True)

    print(f"Attempting to download '{title}' from {pdf_url}...")
    try:
        response = requests.get(pdf_url, stream=True)
        response.raise_for_status() # Raise an HTTPError for bad responses (4xx or 5xx)

        with open(filepath, "wb") as pdf_file:
            for chunk in response.iter_content(chunk_size=8192):
                pdf_file.write(chunk)
        print(f"Successfully downloaded and saved: {filepath}")
        return filepath
    except requests.exceptions.RequestException as e:
        print(f"Error downloading PDF '{title}' from '{pdf_url}': {e}")
        return None

