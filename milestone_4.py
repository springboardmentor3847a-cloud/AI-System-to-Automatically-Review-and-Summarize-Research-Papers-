def evaluate_keyword_presence(text, keywords, section_name):
    """
    Evaluates if specified keywords are present in a given text string.
    """
    missing_keywords = []
    present_keywords = []
    text_lower = text.lower()

    for keyword in keywords:
        if keyword.lower() in text_lower:
            present_keywords.append(keyword)
        else:
            missing_keywords.append(keyword)

    if not missing_keywords:
        return f"✅ All required keywords ({', '.join(present_keywords)}) are present in {section_name}."
    elif not present_keywords:
        return f"❌ None of the required keywords ({', '.join(keywords)}) were found in {section_name}."
    else:
        return f"⚠️ In {section_name}: Present keywords: {', '.join(present_keywords)}. Missing keywords: {', '.join(missing_keywords)}."

